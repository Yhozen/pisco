// node tools/gen-cmd-js.mjs: rt/d3d12_cmd.h's `#define GPU_<NAME> <value>` lines -> web/gpu/cmd.gen.js
import fs from 'node:fs'; import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const defs = [...fs.readFileSync(path.join(root, 'rt/d3d12_cmd.h'), 'utf8').matchAll(/^#define GPU_(\w+) (\d+)$/gm)].map((m) => `  ${m[1]}: ${m[2]},`);
fs.writeFileSync(path.join(root, 'web/gpu/cmd.gen.js'), `// @generated by tools/gen-cmd-js.mjs from rt/d3d12_cmd.h. Do not edit.\nexport const GPU = {\n${defs.join('\n')}\n};\n`);
