# gen-com-layout.py <header.h> <Interface>... > layout.gen.h
# The vtable of each COM interface named, read from a C header written with the DECLARE_INTERFACE macros (the
# mingw-w64 / Wine headers: d3d9.h, dinput.h): the methods in vtable order and, for a 32-bit stdcall caller, the
# bytes of arguments each removes from the stack (`this` included), plus the interface's IID where the header
# gives one. A parameter that is not 4 bytes wide (a double, a 64-bit integer or a structure by value) is an error.
#   python3 tools/gen-com-layout.py $MINGW/i686-w64-mingw32/include/d3d9.h IDirect3D9 IDirect3DDevice9 ... > rt/win32/d3d9_layout.gen.h
import re, sys, os

src = open(sys.argv[1], encoding='utf-8', errors='replace').read()
src = re.sub(r'/\*.*?\*/', ' ', src, flags=re.S)
WIDE = re.compile(r'\b(double|LONGLONG|ULONGLONG|UINT64|INT64|LARGE_INTEGER|ULARGE_INTEGER|REFERENCE_TIME|GUID|D3DMATRIX|D3DVECTOR|D3DCOLORVALUE|DIPROPHEADER)\b(?!\s*\*)(?![^,]*\*)')
blocks = {}
for m in re.finditer(r'DECLARE_INTERFACE_(?:IID_)?\(\s*(\w+)\s*,\s*(\w+)\s*(?:,\s*"([0-9a-fA-F-]+)")?\s*\)\s*\{(.*?)\n\};', src, re.S):
    name, parent, iid, body = m.groups()
    methods = []
    for mm in re.finditer(r'STDMETHOD(?:_\(\s*[^,()]+,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\(\s*THIS_?\s*(.*?)\)\s*PURE\s*;', body, re.S):
        params = ' '.join(mm.group(3).split())
        n = 0 if not params else len(params.split(','))
        if WIDE.search(params): sys.exit(f'gen-com-layout.py: {name}::{mm.group(1) or mm.group(2)} takes a parameter that is not 4 bytes: {params}')
        methods.append((mm.group(1) or mm.group(2), 4 * (1 + n)))
    blocks[name] = (iid, methods)
print('// SPDX-License-' + 'Identifier: LGPL-2.1-or-later')
print(f'// @generated by tools/gen-com-layout.py from {os.path.basename(sys.argv[1])} (mingw-w64, from Wine). Do not edit.')
print('// Each interface\'s methods in vtable order, with the bytes a 32-bit stdcall caller has pushed (`this` included).')
print('#pragma once')
print('#include "com.h"')
for name in sys.argv[2:]:
    if name not in blocks: sys.exit(f'gen-com-layout.py: no interface {name} in {sys.argv[1]}')
    iid, methods = blocks[name]
    print(f'static const ComMethod {name}_methods[] = {{' + ', '.join(f'{{"{n}", {b}}}' for n, b in methods) + '};')
    print(f'static const ComInterface {name}_interface = {{"{name}", "{(iid or "").lower()}", {name}_methods, {len(methods)}}};')
