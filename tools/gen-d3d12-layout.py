#!/usr/bin/env python3
# gen-d3d12-layout.py <xcl d3d12_layout.rs> > rt/d3d12_layout.gen.h
# The PC vtable order of each D3D12 interface family, taken from XCL's table (GPL-2.0), which is generated
# from d3d12.h of microsoft/DirectX-Headers (MIT). Each family gets its most derived interface's methods and
# the IIDs of every version, so QueryInterface can answer for all of them.
import re, sys

src = open(sys.argv[1]).read()
ifaces = {}
for name, iid, parent, methods in re.findall(r'Iface \{ name: "(\w+)", iid: "([^"]+)", parent: "(\w+)", methods: &\[([^\]]*)\] \}', src):
    ifaces[name] = (iid, parent, re.findall(r'"(\w+)"', methods))

families = {  # our class name: the interface family
    'Device': 'ID3D12Device', 'CommandQueue': 'ID3D12CommandQueue', 'CommandAllocator': 'ID3D12CommandAllocator',
    'CommandList': 'ID3D12GraphicsCommandList', 'Fence': 'ID3D12Fence', 'Resource': 'ID3D12Resource',
    'DescriptorHeap': 'ID3D12DescriptorHeap', 'RootSignature': 'ID3D12RootSignature', 'PipelineState': 'ID3D12PipelineState',
    'Heap': 'ID3D12Heap', 'QueryHeap': 'ID3D12QueryHeap', 'CommandSignature': 'ID3D12CommandSignature',
}
out = ['// @generated by tools/gen-d3d12-layout.py from XCL\'s d3d12_layout.rs (d3d12.h, microsoft/DirectX-Headers, MIT). Do not edit.',
       '#pragma once', 'typedef struct { const char *cls, *iface; unsigned count; const char *const *methods; unsigned iid_count; const char *const *iids; } D3dLayout;']
table = []
for cls, base in families.items():
    chain = [n for n in ifaces if n == base or (n.startswith(base) and n[len(base):].isdigit())]
    chain.sort(key=lambda n: len(ifaces[n][2]))
    top = chain[-1]
    methods = ifaces[top][2]
    # the parents' IIDs too (ID3D12Object, ID3D12DeviceChild, ID3D12Pageable, ID3D12CommandList)
    iids, p = [ifaces[n][0] for n in chain], ifaces[base][1]
    while p in ifaces: iids.append(ifaces[p][0]); p = ifaces[p][1]
    iids.append('00000000-0000-0000-c000-000000000046')  # IUnknown
    out.append(f'static const char *const {cls}_methods[] = {{' + ', '.join(f'"{m}"' for m in methods) + '};')
    out.append(f'static const char *const {cls}_iids[] = {{' + ', '.join(f'"{i}"' for i in iids) + '};')
    table.append(f'  {{"{cls}", "{top}", {len(methods)}, {cls}_methods, {len(iids)}, {cls}_iids}},')
out.append('static const D3dLayout d3d_layouts[] = {'); out += table; out.append('};')
print('\n'.join(out))
