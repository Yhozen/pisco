# gen-d3d9-oracle.py [d3d9caps.txt [d3d9probe.txt]] > rt/windows-x86/d3d9_oracle.gen.h
# What the oracle's Direct3D 9 answered (tools/oracle-wine/d3d9caps.txt and d3d9probe.txt, the output of
# d3d9caps.c and d3d9probe.c run under Wine), as C tables for our own Direct3D 9: the device capabilities word by
# word, the adapter's identity and display modes, CheckDeviceFormat's answers, and the state of a new device.
# No number is typed here: a fact our device needs and the files lack is a reason to extend the probe.
import os, struct, sys

here = os.path.dirname(os.path.abspath(__file__))
caps_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, 'oracle-wine', 'd3d9caps.txt')
probe_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, 'oracle-wine', 'd3d9probe.txt')
FLT_MAX = struct.unpack('<f', b'\xff\xff\x7f\x7f')[0]

def f32(text):
    """The bits of the float a %g text stands for. %g keeps six digits, so only a value that survives the round
    trip is taken as it is; the one other value D3DCAPS9 holds is the largest float, which %g shortens."""
    v = float(text); bits = struct.unpack('<I', struct.pack('<f', v))[0]
    if struct.unpack('<f', struct.pack('<I', bits))[0] == v: return bits
    if '%g' % FLT_MAX == text: return 0x7F7FFFFF
    sys.exit(f'gen-d3d9-oracle.py: {text} is not a float written exactly')

# D3DCAPS9: every field is four bytes, in the order d3d9caps.c prints them (the structure's own); 76 fields, 304 bytes
words = []; names = []
for line in open(caps_path):
    if line.startswith('#') or not line.strip(): continue
    name, value = line.split()
    words.append(int(value, 16) if value.startswith('0x') else f32(value)); names.append(name)
if len(words) != 76: sys.exit(f'gen-d3d9-oracle.py: {caps_path} has {len(words)} fields, D3DCAPS9 has 76')

facts = {}; modes = []; formats = []; rs = []; tss = []; samp = []; queries = []; depth = []; types = []; blocks = {}
for line in open(probe_path):
    p = line.split()
    if not p or p[0] in ('#', 'note'): continue
    k = p[0]
    if k == 'mode': modes.append(tuple(int(x) for x in p[1:]))
    elif k == 'format': formats.append((int(p[1]), int(p[2], 16), int(p[3]), int(p[4], 16)))
    elif k == 'rs': rs.append((int(p[1]), int(p[2], 16)))
    elif k == 'tss': tss.append((int(p[1]), int(p[2]), int(p[3], 16)))
    elif k == 'samp': samp.append((int(p[1]), int(p[2]), int(p[3], 16)))
    elif k == 'query': queries.append((int(p[1]), int(p[2], 16)))
    elif k == 'depth_match': depth.append((int(p[1]), int(p[2]), int(p[3], 16)))
    elif k == 'device_type': types.append((int(p[1]), int(p[2]), int(p[3], 16)))
    elif k == 'stateblock': blocks[(int(p[1]), p[2])] = p[3:]
    else: facts[k] = line.split(None, 1)[1].rstrip('\n') if len(p) > 1 else ''
need = ['driver', 'description', 'device_name', 'driver_version', 'vendor', 'device', 'subsys', 'revision', 'whql', 'identifier', 'display', 'material', 'light', 'texture_mem', 'adapters']
missing = [k for k in need if k not in facts]
if missing: sys.exit(f'gen-d3d9-oracle.py: {probe_path} lacks {missing}')
cstr = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
hexes = lambda vals: ', '.join(f'{v:#x}' for v in vals)
rows = lambda items, fmt: ', '.join('{' + fmt(*i) + '}' for i in items)

out = []
out.append('// SPDX-License-' + 'Identifier: GPL-2.0-or-later')
out.append('// @generated by tools/gen-d3d9-oracle.py from tools/oracle-wine/d3d9caps.txt and d3d9probe.txt. Do not edit.')
out.append('// What the oracle\'s Direct3D 9 (Wine on this machine) answers: our device gives the same answers.')
out.append('#pragma once')
out.append('// D3DCAPS9, word by word: ' + ', '.join(names[:6]) + ', ...')
out.append(f'static const u32 oracle_caps[{len(words)}] = {{{hexes(words)}}};')
out.append(f'static const char oracle_driver[] = {cstr(facts["driver"])}, oracle_description[] = {cstr(facts["description"])}, oracle_device_name[] = {cstr(facts["device_name"])};')
hi, lo = facts['driver_version'].split()
out.append(f'static const u32 oracle_driver_version_high = {hi}, oracle_driver_version_low = {lo}, oracle_vendor = {facts["vendor"]}, oracle_device = {facts["device"]}, '
           f'oracle_subsys = {facts["subsys"]}, oracle_revision = {facts["revision"]}, oracle_whql = {facts["whql"]}, oracle_adapters = {facts["adapters"]}, oracle_texture_mem = {facts["texture_mem"]};')
out.append('static const u8 oracle_identifier[16] = {' + ', '.join('0x' + b for b in facts['identifier'].split()) + '};')
w, h, hz, fmt = facts['display'].split()
out.append(f'static const struct {{ u32 width, height, refresh, format; }} oracle_display = {{{w}, {h}, {hz}, {fmt}}};')
out.append('// the display modes EnumAdapterModes lists for a format: the format asked for, then the mode')
out.append('static const struct { u32 asked, index, width, height, refresh, format; } oracle_modes[] = {' + rows(modes, lambda *m: ', '.join(str(x) for x in m)) + '};')
out.append('// CheckDeviceFormat against an X8R8G8B8 display on the HAL device: format, usage, resource type, the answer')
out.append('static const struct { u32 format, usage, type, hr; } oracle_formats[] = {\n  ' + ',\n  '.join(rows(formats[i:i + 8], lambda f, u, t, r: f'{f}, {u:#x}, {t}, {r:#x}') for i in range(0, len(formats), 8)) + '};')
out.append('// CheckDepthStencilMatch (render target format, depth format) and CheckDeviceType (back buffer format, windowed)')
out.append('static const struct { u32 target, depth, hr; } oracle_depth_match[] = {' + rows(depth, lambda a, b, r: f'{a}, {b}, {r:#x}') + '};')
out.append('static const struct { u32 format, windowed, hr; } oracle_device_types[] = {' + rows(types, lambda a, b, r: f'{a}, {b}, {r:#x}') + '};')
out.append('// a new device: render states, texture stage states (stage, state), sampler states (sampler, state)')
out.append('static const struct { u32 state, value; } oracle_render_states[] = {\n  ' + ',\n  '.join(rows(rs[i:i + 12], lambda s, v: f'{s}, {v:#x}') for i in range(0, len(rs), 12)) + '};')
out.append('static const struct { u8 stage, state; u32 value; } oracle_stage_states[] = {\n  ' + ',\n  '.join(rows(tss[i:i + 12], lambda a, s, v: f'{a}, {s}, {v:#x}') for i in range(0, len(tss), 12)) + '};')
out.append('static const struct { u16 sampler; u8 state; u32 value; } oracle_sampler_states[] = {\n  ' + ',\n  '.join(rows(samp[i:i + 12], lambda a, s, v: f'{a}, {s}, {v:#x}') for i in range(0, len(samp), 12)) + '};')
# What a state block of type D3DSBT_PIXELSTATE (2) and D3DSBT_VERTEXSTATE (3) covers. The probe tries every number;
# only the states Direct3D 9 defines are kept (their names are in oracle-wine/summarize.py).
src = open(os.path.join(here, 'oracle-wine', 'summarize.py')).read(); names = {}; exec(src[src.index('RS = {'):src.index('TS = {')], names)
out.append('// CreateStateBlock: the render, texture stage and sampler states a pixel-state block and a vertex-state block cover')
for t, kind in ((2, 'pixel'), (3, 'vertex')):
    for what, table in (('rs', 'RS'), ('tss', 'TSS'), ('samp', 'SAMP')):
        if (t, what) not in blocks: sys.exit(f'gen-d3d9-oracle.py: {probe_path} lacks "stateblock {t} {what}"')
        out.append(f'static const u8 oracle_{kind}_{what}[] = {{' + ', '.join(v for v in blocks[(t, what)] if int(v) in names[table]) + '};')
    out.append(f'// and of the rest: ' + ' '.join(blocks.get((t, 'other'), [])))
mat = facts['material'].split()
out.append(f'static const u32 oracle_material[{len(mat)}] = {{{hexes(f32(x) for x in mat)}}};   // D3DMATERIAL9, as float bits')
light = facts['light'].split('(')[0].split()
out.append(f'// D3DLIGHT9 of a light that was enabled without being set: its type, then the {len(light) - 1} floats after it, as bits')
out.append(f'static const u32 oracle_light[{len(light)}] = {{{light[0]}, {hexes(f32(x) for x in light[1:])}}};')
print('\n'.join(out))
