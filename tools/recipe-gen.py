# recipe-gen.py [recipe.json] > recipe.gen.c: what an app's recipe says, for the runtime (rt/rt.h has the types).
# It reads the recipe as `pisco recipe <dir> --json` writes it (pisco is the one reader of recipe.toml:
# docs/spec/recipe.md): cpu.features (the virtual CPU; without it, every feature the lifter supports), the registry
# (key, name, type, value), quirks.heap_fill. With no recipe: the defaults.
# recipe-gen.py --lifter-options recipe.json prints the lifter's options the recipe implies instead:
# `--builtin name.dll` for each `[dll] "name.dll" = "builtin"` (a shipped DLL the runtime answers for).
import sys, json

if len(sys.argv) > 2 and sys.argv[1] == '--lifter-options':
    dlls = json.load(open(sys.argv[2])).get('dll', {})
    print(' '.join(f'--builtin {name}' for name, how in dlls.items() if how == 'builtin')); sys.exit(0)
recipe = json.load(open(sys.argv[1])) if len(sys.argv) > 1 else {}
BITS = {'fpu': 1, 'tsc': 2, 'cx8': 4, 'cmov': 8, 'mmx': 0x10, 'fxsr': 0x20, 'sse': 0x40, 'sse2': 0x80, 'sse3': 0x100, 'ssse3': 0x200,
        'sse4.1': 0x400, 'sse4.2': 0x800, 'popcnt': 0x1000, 'cx16': 0x2000, 'pclmul': 0x4000}
features = (recipe.get('cpu') or {}).get('features')
if features is None: mask = sum(BITS.values())
else:
    unknown = [f for f in features if f not in BITS]
    if unknown: sys.exit(f'recipe-gen.py: unknown CPU features {unknown}; known: {sorted(BITS)}')
    mask = sum(BITS[f] for f in features)
cstr = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
print('// @generated by tools/recipe-gen.py' + (f' from {sys.argv[1]}' if len(sys.argv) > 1 else ' (no recipe: the defaults)') + '. Do not edit.')
print('#include "rt.h"')
print(f'const unsigned rt_cpu_features = {mask:#x};')
rows = []
for v in recipe.get('registry') or []:
    sz = v['type'] == 'sz'
    rows.append(f'  {{{cstr(v["key"])}, {cstr(v["name"])}, {cstr(v["value"]) if sz else "0"}, {0 if sz else v["value"]}}},')
print('const RegistryValue rt_registry[] = {'); print('\n'.join(rows)); print('  {0, 0, 0, 0}};')
print(f'const unsigned rt_registry_count = {len(rows)};')
# [quirks] heap_fill = 0xCD: what a heap block the app did not ask to be zeroed holds (kernel32's HeapAlloc);
# without it, whatever the runtime's allocator left there
fill = (recipe.get('quirks') or {}).get('heap_fill')
if fill is not None and not (isinstance(fill, int) and 0 <= fill <= 255): sys.exit(f'recipe-gen.py: quirks.heap_fill is a byte, not {fill!r}')
print(f'const int rt_heap_fill = {-1 if fill is None else fill};')
